# ──────────────────────────────────────────────────────────────────────────────
#  MANAGEMENT COMMAND
# ──────────────────────────────────────────────────────────────────────────────

class Command(BaseCommand):
    help = 'Seed 400 realistic DigitalGig listings across all digital skill categories.'

    def add_arguments(self, parser):
        parser.add_argument(
            '--dry-run', action='store_true',
            help='Preview what would be created without writing to the database.',
        )
        parser.add_argument(
            '--clear', action='store_true',
            help='Delete all gigs posted by the seed employer before seeding.',
        )

    def handle(self, *args, **options):
        dry_run = options['dry_run']
        do_clear = options['clear']

        # ── 1. Get or create seed employer ────────────────────────────────────
        employer_profile = self._get_or_create_employer()

        if do_clear:
            deleted, _ = DigitalGig.objects.filter(employer=employer_profile).delete()
            self.stdout.write(self.style.WARNING(
                f'🗑  Cleared {deleted} existing seed digital gigs.'
            ))

        # ── 2. Load all categories and sub-skills ─────────────────────────────
        categories = {c.slug: c for c in DigitalSkillCategory.objects.all()}
        if not categories:
            self.stdout.write(self.style.ERROR(
                '❌  No DigitalSkillCategory records found.\n'
                '    Run:  python manage.py seed_digital_skill_categories  first.'
            ))
            return

        sub_skills_by_category = {}
        for slug, cat in categories.items():
            sub_skills_by_category[slug] = list(
                DigitalSubSkill.objects.filter(category=cat)
            )

        # ── 3. Seed gigs ──────────────────────────────────────────────────────
        created_count  = 0
        skipped_count  = 0
        total_target   = 0

        with transaction.atomic():
            for cat_slug, gig_list in GIGS_BY_CATEGORY.items():
                cat = categories.get(cat_slug)
                if not cat:
                    self.stdout.write(self.style.WARNING(
                        f'  ⚠  Category not found in DB: {cat_slug} — skipping.'
                    ))
                    continue

                available_sub_skills = sub_skills_by_category.get(cat_slug, [])
                total_target += len(gig_list)

                for (title, description, budget_type, bmin, bmax) in gig_list:
                    if dry_run:
                        self.stdout.write(f'  [DRY-RUN] Would create: {title[:70]}')
                        created_count += 1
                        continue

                    # Idempotency: skip if same title+employer already exists
                    if DigitalGig.objects.filter(
                        employer=employer_profile, title=title
                    ).exists():
                        skipped_count += 1
                        continue

                    # Random metadata
                    work_type = random.choice(WORK_TYPES)
                    state     = random.choice(NG_STATES) if work_type != 'remote' else random.choice(NG_STATES[:8])
                    deadline  = date.today() + timedelta(days=random.randint(14, 90))

                    gig = DigitalGig.objects.create(
                        employer    = employer_profile,
                        title       = title,
                        description = description,
                        category    = cat,
                        budget_type = budget_type,
                        budget_min  = bmin,
                        budget_max  = bmax,
                        work_type   = work_type,
                        state       = state,
                        deadline    = deadline,
                        status      = DigitalGig.Status.ACTIVE,
                    )

                    # Attach 1–3 random sub-skills
                    if available_sub_skills:
                        chosen = random.sample(
                            available_sub_skills,
                            k=min(random.randint(1, 3), len(available_sub_skills))
                        )
                        gig.required_sub_skills.set(chosen)

                    created_count += 1

        # ── 4. Summary ────────────────────────────────────────────────────────
        if dry_run:
            self.stdout.write(self.style.SUCCESS(
                f'\n🔍  DRY-RUN: Would create {created_count} digital gigs '
                f'across {len(GIGS_BY_CATEGORY)} categories.'
            ))
        else:
            self.stdout.write(self.style.SUCCESS(
                f'\n✅  Seeded {created_count} new digital gigs '
                f'({skipped_count} already existed).'
            ))
            self.stdout.write(
                f'    Categories: {len(GIGS_BY_CATEGORY)} | '
                f'Target: {total_target} | Employer: {SEED_EMPLOYER_USERNAME}'
            )

    # ── Helpers ───────────────────────────────────────────────────────────────

    def _get_or_create_employer(self) -> EmployerProfile:
        """Return (creating if needed) the seed employer and their EmployerProfile."""
        User = __import__('django.contrib.auth', fromlist=['get_user_model']).get_user_model()

        user, user_created = User.objects.get_or_create(
            username=SEED_EMPLOYER_USERNAME,
            defaults={
                'email':        SEED_EMPLOYER_EMAIL,
                'account_type': 'employer',
                'is_active':    True,
            },
        )
        if user_created:
            user.set_password('SeedPass!2026')
            user.save()
            self.stdout.write(f'  Created seed employer user: {SEED_EMPLOYER_USERNAME}')
        else:
            self.stdout.write(f'  Using existing seed employer: {SEED_EMPLOYER_USERNAME}')

        profile, _ = EmployerProfile.objects.get_or_create(
            user=user,
            defaults={
                'company_name':     SEED_EMPLOYER_COMPANY,
                'description':      'TradeLink NG seed data employer for digital gigs.',
                'industry_sector':         'Technology',
                'state':            'Lagos',
                'is_verified':      True,
            },
        )
        return profile
